def get_character(character_id: str) -> Character:
    """Получить персонажа по ID"""
    return CHARACTERS.get(character_id)


def get_all_characters_info() -> str:
    """Получить информацию о всех персонажах"""
    result = "👥 *ПЕРСОНАЖИ*\n\n"
    for char in CHARACTERS.values():
        result += f"{char.emoji} *{char.name}*, {char.age}\n"
        result += f"_{char.occupation}_\n"
        result += f"{char.description[:150]}...\n\n"
    return result
"""
Персонажи игры
"""
from dataclasses import dataclass
from typing import Dict


@dataclass
class Character:
    """Класс персонажа"""
    id: str
    name: str
    age: int
    occupation: str
    description: str
    personality: str
    appearance: str
    likes: list
    dislikes: list
    secret: str  # Скрытая информация, раскрывается по мере игры
    emoji: str  # Эмодзи для отображения
    
    def get_full_info(self) -> str:
        """Полная информация о персонаже"""
        return f"""
{self.emoji} *{self.name}*, {self.age} лет
_{self.occupation}_

📝 *О персонаже:*
{self.description}

💫 *Характер:*
{self.personality}

👤 *Внешность:*
{self.appearance}

❤️ *Любит:* {', '.join(self.likes)}
💔 *Не любит:* {', '.join(self.dislikes)}
"""

    def get_short_info(self) -> str:
        """Краткая информация"""
        return f"{self.emoji} *{self.name}* — {self.occupation}"


